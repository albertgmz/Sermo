/**
 * Inputs written to be slow or to break out of the renderer, at most 10,000 characters each: the
 * ones that made Markdown parsers slow (kept as text now), shapes of BB code that unclosed,
 * misnested and repeated tags can take, and mixes of both. Used by the timing test.
 */
const LIMIT = 10_000;

const fill = (unit: string, limit = LIMIT): string => unit.repeat(Math.floor(limit / unit.length));
const half = (open: string, close: string): string =>
  fill(open, LIMIT / 2) + fill(close, LIMIT / 2);

export interface AdversarialInput {
  name: string;
  source: string;
  /** Needs the database (mentions, quotes) and so is rendered with an actor. */
  withActor?: boolean;
}


// The entries with their labels in the viewer's language, in the order of the grid.
export function labelledIcons(label: (key: IconName) => string): IconEntry[] {
  return ICON_KEYWORDS.map((entry) => ({ ...entry, label: label(entry.key) }));
}

// The entries that match a search: every word typed must appear in the key, the label or the
// search words. An empty search matches all of them, in the order of the grid.
export function searchIcons(query: string, entries: IconEntry[]): IconEntry[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return entries;
  return entries.filter((entry) => {
    const haystack =
      `${entry.key} ${entry.label} ${entry.keywords}`.toLowerCase();
    return words.every((word) => haystack.includes(word));
  });
}
